function getCurrentLang() {
    return localStorage.getItem('edufind_lang') || 'en';
}

function setLang(lang) {
    if (!TRANSLATIONS[lang]) lang = 'en';
    localStorage.setItem('edufind_lang', lang);
    applyLanguage(lang);
    window.dispatchEvent(new CustomEvent('languageChanged', { detail: { lang } }));
}

function t(key) {
    const lang = getCurrentLang();
    return (TRANSLATIONS[lang] && TRANSLATIONS[lang][key]) || (TRANSLATIONS['en'][key] || key);
}

function applyLanguage(lang) {
    if (!lang) lang = getCurrentLang();

    // 1. Text elements with data-i18n
    document.querySelectorAll('[data-i18n]').forEach(el => {
        const key = el.getAttribute('data-i18n');
        if (key && TRANSLATIONS[lang] && TRANSLATIONS[lang][key]) {
            el.textContent = TRANSLATIONS[lang][key];
        }
    });

    // 2. Placeholders with data-i18n-placeholder
    document.querySelectorAll('[data-i18n-placeholder]').forEach(el => {
        const key = el.getAttribute('data-i18n-placeholder');
        if (key && TRANSLATIONS[lang] && TRANSLATIONS[lang][key]) {
            el.placeholder = TRANSLATIONS[lang][key];
        }
    });

    // 3. Update select dropdowns with class .lang-select
    document.querySelectorAll('.lang-select').forEach(sel => {
        sel.value = lang;
    });

    // 4. Update html lang attribute
    document.documentElement.lang = lang;
}

// Auto-run on DOMContentLoaded
if (document.readyState === 'loading') {
    document.addEventListener('DOMContentLoaded', () => applyLanguage(getCurrentLang()));
} else {
    applyLanguage(getCurrentLang());
}
